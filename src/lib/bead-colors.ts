export type BrandColors = Record<string, [string, string, number, number, number][]>;

export const PALETTES: Record<string, { name: string; colors: [string, string, number, number, number][] }> = {
  perler: { name: "Perler", colors: PERLER_COLORS },
  hama: { name: "Hama", colors: HAMA_COLORS },
  artkal: { name: "Artkal", colors: ARTKAL_COLORS },
};

// Brand cross-reference mapping for converter
export const BRAND_NAMES = { perler: "Perler", hama: "Hama", artkal: "Artkal" } as const;

export function colorDistance(rgb1: [number, number, number], rgb2: [number, number, number]): number {
  const rmean = (rgb1[0] + rgb2[0]) / 2;
  const dr = rgb1[0] - rgb2[0];
  const dg = rgb1[1] - rgb2[1];
  const db = rgb1[2] - rgb2[2];
  return Math.sqrt(((512 + rmean) * dr * dr) / 256 + 4 * dg * dg + ((767 - rmean) * db * db) / 256);
}

export function findClosestColor(
  pixel: [number, number, number],
  colors: [string, string, number, number, number][]
): [string, string, number, number, number] {
  let best = colors[0];
  let bestDist = Infinity;
  for (const c of colors) {
    const d = colorDistance(pixel, [c[2], c[3], c[4]]);
    if (d < bestDist) { bestDist = d; best = c; }
  }
  return best;
}

// Cross-brand color conversion
export function convertColor(
  sourceCode: string,
  fromBrand: string,
  toBrand: string
): [string, string, number, number, number] | null {
  const fromColors = PALETTES[fromBrand]?.colors;
  const toColors = PALETTES[toBrand]?.colors;
  if (!fromColors || !toColors) return null;
  
  const source = fromColors.find(c => c[0] === sourceCode);
  if (!source) return null;
  
  return findClosestColor([source[2], source[3], source[4]], toColors);
}
