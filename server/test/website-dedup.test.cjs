const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'website-dedup-'));
process.env.DB_PATH = path.join(temporary, 'test.db');
process.env.DATABASE_URL = '';
process.env.JWT_SECRET = 'website-dedup-isolated-test-secret';
process.env.RESOURCE_REGISTRY_KEY = 'resource-registry-isolated-test-secret-12345';
process.env.RESOURCE_REGISTRY_SITE_PROJECT = 'PRJ-0008';
process.env.RESOURCE_REGISTRY_BACKFILL_COMPLETE = 'yes';
const express = require('express');
const { query } = require('../dist/config/db');
require('../dist/config/db').enableResourceRegistryMigration();
const { signToken } = require('../dist/middleware/auth');
const app = express();
app.use(express.json());
app.use('/projects', require('../dist/routes/projects').projectsRouter);
app.use('/admin', require('../dist/routes/admin').adminRouter);
app.use('/registry', require('../dist/routes/resource-registry').resourceRegistryRouter);
app.use((error, _req, res, _next) => res.status(error.status || 500).json({ error: error.message }));

test('website preview does not reserve and submissions block duplicates', async t => {
  const user = async (name, admin = 0) => {
    const { insertId } = await query('INSERT INTO users (username,email,password_hash,email_verified,is_admin) VALUES (?, ?, ?, 1, ?)', [name, `${name}@example.invalid`, 'unused', admin]);
    return signToken({ userId: insertId, plan: 'free' });
  };
  const author = await user('author'), other = await user('other'), admin = await user('admin', 1);
  const server = await new Promise(resolve => { const running = app.listen(0, '127.0.0.1', () => resolve(running)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(temporary, { recursive: true, force: true }); });
  const request = async (url, token, method = 'GET', body) => {
    const response = await fetch(base + url, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  };
  const draft = { title: '共享仓库', summary: '介绍这个工具', category: 'GitHub 实用项目', repoUrl: 'https://github.com/OWNER/Repo', acceptedRules: true };
  const guardAuthor = await user('guard-author');
  assert.equal((await request('/projects', guardAuthor, 'POST', draft)).status, 503, '回填前不能投稿');
  await require('../dist/resource-backfill').backfillResources('PRJ-0008', '网站', [], true);
  const configuredProject = process.env.RESOURCE_REGISTRY_SITE_PROJECT;
  delete process.env.RESOURCE_REGISTRY_SITE_PROJECT;
  assert.equal((await request('/projects', guardAuthor, 'POST', draft)).status, 503, '移除配置不能绕过查重');
  process.env.RESOURCE_REGISTRY_SITE_PROJECT = 'PRJ-9999';
  assert.equal((await request('/projects', guardAuthor, 'POST', draft)).status, 503, '变更项目不能绕过查重');
  process.env.RESOURCE_REGISTRY_SITE_PROJECT = configuredProject;
  const preview = { requestId: 'feishu:preview', project: 'PRJ-0008', channel: '网站', url: 'https://github.com/owner/preview', preview: true };
  assert.deepEqual((await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', preview)).data, { duplicate: false, preview: true });
  assert.equal((await query('SELECT id FROM resource_entries')).length, 0, '预查不能占用登记');
  assert.equal((await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { ...preview, channel: '其他频道' })).status, 400);
  const previewAuthor = await user('preview-author');
  const previewPost = await request('/projects', previewAuthor, 'POST', { ...draft, repoUrl: preview.url });
  assert.equal(previewPost.status, 201, '预查后应能直接通过网站表单投稿');
  assert.equal((await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', preview)).data.duplicate, true, '投稿后预查应发现登记');
  assert.equal((await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { requestId: 'feishu:bad-config', project: 'PRJ-0008', channel: '网站 ', url: draft.repoUrl })).status, 409);
  const reservation = await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { requestId: 'cli:task-1', project: 'PRJ-0008', channel: '网站', url: draft.repoUrl, reserveWebsite: true });
  assert.equal(reservation.status, 409, '网站预登记必须拒绝，避免永久占位');
  assert.equal((await query('SELECT id FROM resource_entries')).length, 1, '被拒绝的预登记不能占位');
  const created = await request('/projects', author, 'POST', draft);
  assert.equal(created.status, 201);
  assert.equal((await request('/projects', other, 'POST', { ...draft, title: '重复投稿' })).status, 409);
  let project = (await request(`/projects/${created.data.id}`, author)).data;
  assert.equal((await request(`/projects/${project.id}`, author, 'PUT', { ...draft, revision: project.revision, summary: '更新介绍' })).status, 200);
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'approve', revision: project.revision })).status, 200);
  const removalAuthor = await user('removal-author');
  const removal = await request('/projects', removalAuthor, 'POST', { ...draft, repoUrl: 'https://github.com/owner/removal' });
  assert.equal(removal.status, 201);
  const readyValue = (await query("SELECT setting_value FROM system_settings WHERE setting_key = 'resource_registry_ready'"))[0].setting_value;
  assert.equal((await request('/admin/settings', admin)).data.resource_registry_ready, undefined);
  assert.equal((await request('/admin/settings', admin, 'PUT', [{ key: 'resource_registry_ready', value: '' }])).status, 400);
  assert.equal((await query("SELECT setting_value FROM system_settings WHERE setting_key = 'resource_registry_ready'"))[0].setting_value, readyValue);
  delete process.env.RESOURCE_REGISTRY_SITE_PROJECT;
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'feature', revision: project.revision })).status, 200);
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'softDelete', note: '紧急下架', revision: project.revision })).status, 200);
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'restore', revision: project.revision })).status, 503, '配置异常时不能恢复发布流程');
  assert.equal((await request(`/projects/${removal.data.id}/withdraw`, removalAuthor, 'POST', { revision: 1 })).status, 200);
  assert.equal((await query('SELECT is_released FROM resource_entries WHERE website_project_id = ?', [removal.data.id]))[0].is_released, 0, '配置异常时保留登记，避免重复收录');
  process.env.RESOURCE_REGISTRY_SITE_PROJECT = configuredProject;
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'restore', revision: project.revision })).status, 200);
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/admin/projects/${project.id}`, admin, 'PUT', { action: 'approve', revision: project.revision })).status, 200);
  const duplicate = await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { requestId: 'other-channel', project: 'PRJ-0008', channel: '其他频道', url: draft.repoUrl });
  assert.equal(duplicate.data.duplicate, true);
  assert.equal(duplicate.data.existing.channel, '网站');
  assert.equal(duplicate.data.claimToken, undefined);
  const concurrentA = await user('concurrent-a'), concurrentB = await user('concurrent-b');
  const fresh = { ...draft, title: '并发投稿', repoUrl: 'https://github.com/owner/concurrent' };
  const attempts = await Promise.all([concurrentA, concurrentB].map(token => request('/projects', token, 'POST', fresh)));
  assert.deepEqual(attempts.map(item => item.status).sort(), [201, 409]);
  const forged = await user('forged');
  assert.equal((await request('/projects', forged, 'POST', { ...draft, repoUrl: 'https://github.com/owner/different', registryProof: { requestId: 'old', token: 'old' } })).status, 400);
  const outsider = await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { requestId: 'outsider', project: 'PRJ-0008', channel: '其他频道', url: 'https://github.com/owner/other-channel' });
  assert.equal(outsider.data.duplicate, false);
  assert.equal((await request('/projects', forged, 'POST', { ...draft, repoUrl: 'https://github.com/owner/other-channel' })).status, 409);
  project = (await request(`/projects/${project.id}`, author)).data;
  assert.equal((await request(`/projects/${project.id}/withdraw`, author, 'POST', { revision: project.revision })).status, 200);
  assert.equal((await request('/registry/check', process.env.RESOURCE_REGISTRY_KEY, 'POST', { requestId: 'after-withdraw', project: 'PRJ-0008', channel: '其他频道', url: draft.repoUrl })).data.duplicate, true);
  delete process.env.RESOURCE_REGISTRY_BACKFILL_COMPLETE;
  assert.equal((await request('/projects', author, 'POST', { ...draft, title: '未启用回填', repoUrl: 'https://github.com/owner/new-repo' })).status, 503);
  assert.equal((await request('/projects/mine', author)).data.length, 1, '失败时作品和登记应一起回滚');
});
