const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'resource-registry-'));
process.env.DB_PATH = path.join(temporary, 'test.db');
process.env.DATABASE_URL = '';
process.env.RESOURCE_REGISTRY_KEY = 'test-key-not-valid-outside-this-test-123456789';
const express = require('express');
const { resourceRegistryRouter } = require('../dist/routes/resource-registry');
const app = express();
app.use(express.json());
app.use('/registry', resourceRegistryRouter);
app.use((error, _req, res, _next) => res.status(error.status || 500).json({ error: error.message }));

test('shared registry handles authentication, retries, collisions and concurrent requests', async t => {
  const server = await new Promise(resolve => { const running = app.listen(0, '127.0.0.1', () => resolve(running)); });
  const url = `http://127.0.0.1:${server.address().port}/registry/check`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(temporary, { recursive: true, force: true }); });
  const request = async (body, key = process.env.RESOURCE_REGISTRY_KEY) => {
    const response = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` }, body: JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  };
  const first = { requestId: 'one', project: 'PRJ-0001', channel: '频道甲', url: 'http://github.com/Owner/Example.GIT/?utm_source=test#section' };
  assert.equal((await request(first, 'incorrect-key')).status, 401);
  const created = await request(first);
  assert.equal(created.status, 200);
  assert.equal(created.data.duplicate, false);
  assert.deepEqual(await request(first), created);
  assert.equal((await request({ ...first, channel: '不同频道' })).status, 409);
  const duplicate = await request({ ...first, requestId: 'two', channel: '频道乙', url: 'https://github.com/owner/example' });
  assert.equal(duplicate.data.duplicate, true);
  assert.equal(duplicate.data.existing.channel, '频道甲');
  assert.equal((await request({ ...first, requestId: 'github-query', url: 'https://github.com/owner/example?tab=readme-ov-file' })).data.duplicate, true);
  assert.equal((await request({ requestId: 'spa-a', project: 'PRJ-0002', channel: '频道甲', url: 'https://example.com/#/tool-a' })).data.duplicate, false);
  assert.equal((await request({ requestId: 'spa-b', project: 'PRJ-0002', channel: '频道甲', url: 'https://example.com/#/tool-b' })).data.duplicate, false);
  const content = '这是一段完整内容，用来验证不同来源的相同内容会被识别为重复，必须达到指定的最低字数。';
  const contentEntry = await request({ requestId: 'three', project: 'PRJ-0002', channel: '频道丙', content });
  assert.equal(contentEntry.data.duplicate, false);
  assert.equal((await request({ requestId: 'four', project: 'PRJ-0002', channel: '频道丁', content, url: first.url })).status, 409);
  const common = { project: 'PRJ-0003', channel: '频道戊', url: 'https://example.com/unique-resource' };
  const concurrent = await Promise.all(['five', 'six'].map(requestId => request({ ...common, requestId })));
  assert.equal(concurrent.filter(item => item.status === 200 && item.data.duplicate === false).length, 1);
  assert.equal(concurrent.filter(item => item.status === 200 && item.data.duplicate === true).length, 1);
  assert.equal((await request({ requestId: 'invalid', project: 'PRJ-0001', channel: '频道', url: 'file:///private' })).status, 400);
  delete process.env.RESOURCE_REGISTRY_KEY;
  assert.equal((await request(first, 'any')).status, 503);
});
